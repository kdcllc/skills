#!/usr/bin/env bash
set -euo pipefail

# Usage: scripts/checks/agent-composer.sh [repo-root]
# Content-contract guards for the agent-composer skill: required files, pinned
# phrases, Cursor template shape, and no concrete model IDs in shipped docs.
# Run by scripts/validate-skills.sh.

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
SKILL_DIR="skills/agent-composer"
SKILL="${ROOT}/${SKILL_DIR}"

fail() {
  echo "error: agent-composer: $*" >&2
  exit 1
}

REQUIRED_PATHS=(
  "${SKILL_DIR}/SKILL.md"
  "${SKILL_DIR}/CHANGELOG.md"
  "${SKILL_DIR}/references/spec-schema.md"
  "${SKILL_DIR}/references/claude-code.md"
  "${SKILL_DIR}/references/cursor.md"
  "${SKILL_DIR}/references/patterns.md"
  "${SKILL_DIR}/references/writing-agents.md"
  "${SKILL_DIR}/assets/templates/README.md"
  "${SKILL_DIR}/assets/templates/claude-agent.md.tmpl"
  "${SKILL_DIR}/assets/templates/cursor-agent.md.tmpl"
  "${SKILL_DIR}/assets/templates/orchestrator-skill.md.tmpl"
  "${SKILL_DIR}/assets/templates/cursor-rule.mdc.tmpl"
  "${SKILL_DIR}/assets/examples/coding-crew.crew.yaml"
  "${SKILL_DIR}/assets/examples/content-crew.crew.yaml"
  "${SKILL_DIR}/assets/examples/triage-crew.crew.yaml"
  "${SKILL_DIR}/scripts/validate.sh"
  "${SKILL_DIR}/scripts/manifest.sh"
  "${SKILL_DIR}/scripts/composer.py"
)

MODEL_ID_PATTERN='(claude|gpt|gemini|composer|opus|sonnet|haiku)-[0-9]'

check_required_paths() {
  local rel
  for rel in "${REQUIRED_PATHS[@]}"; do
    [[ -e "${ROOT}/${rel}" ]] || fail "missing required path: ${rel}"
  done
}

check_pinned_phrases() {
  grep -qF 'Do not generate any file until the user confirms the spec.' "${SKILL}/SKILL.md" ||
    fail "SKILL.md missing confirmation gate phrase"
  grep -qF 'The generator never writes `tools:` for Cursor agents.' "${SKILL}/references/cursor.md" ||
    fail "references/cursor.md missing Cursor tools rule"
  grep -qF '<!-- generated by agent-composer from .agent-composer/<name>.crew.yaml' \
    "${SKILL}/references/spec-schema.md" ||
    fail "references/spec-schema.md missing generated-by marker"
}

check_cursor_template() {
  local tmpl="${SKILL}/assets/templates/cursor-agent.md.tmpl"
  if grep -qE '^tools:' "$tmpl"; then
    fail "cursor-agent.md.tmpl must not contain a top-level tools: line"
  fi
  if grep -qE '^model: "' "$tmpl"; then
    fail 'cursor-agent.md.tmpl must not contain a quoted model: " line'
  fi
}

check_no_concrete_model_ids() {
  local matches dir
  for dir in references assets/templates; do
    matches="$(grep -rEn "$MODEL_ID_PATTERN" "${SKILL}/${dir}" 2>/dev/null || true)"
    if [[ -n "$matches" ]]; then
      echo "$matches" >&2
      fail "concrete model ID found in ${dir}/"
    fi
  done
  matches="$(grep -En "$MODEL_ID_PATTERN" "${SKILL}/SKILL.md" 2>/dev/null || true)"
  if [[ -n "$matches" ]]; then
    echo "$matches" >&2
    fail "concrete model ID found in SKILL.md"
  fi
}

check_required_paths
check_pinned_phrases
check_cursor_template
check_no_concrete_model_ids
