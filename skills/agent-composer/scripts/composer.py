def check_string_enum(
    findings: List[Finding],
    spec_path: str,
    yaml_path: str,
    value: Any,
    allowed: frozenset,
    invalid_message: str,
) -> bool:
    if not isinstance(value, str):
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_path, yaml_path),
                invalid_message,
            )
        )
        return False
    if value not in allowed:
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_path, yaml_path),
                invalid_message,
            )
        )
        return False
    return True


def check_name_id(
    findings: List[Finding],
    spec_path: str,
    value: Any,
    yaml_path: str,
) -> bool:
    if not isinstance(value, str):
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_path, yaml_path),
                "must be a string",
            )
        )
        return False
    if not NAME_RE.match(value):
        findings.append(
            Finding(
                "error",
                "S007",
                spec_loc(spec_path, yaml_path),
                "must match ^[a-z0-9]+(-[a-z0-9]+)*$",
            )
        )
        return False
    if len(value) < 1 or len(value) > 64:
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_path, yaml_path),
                "must be 1–64 characters",
            )
        )
        return False
    return True


def agent_used_in_steps(agent_id: str, steps: List[dict]) -> bool:
    for step in steps:
        if not isinstance(step, dict):
            continue
        if step.get("agent") == agent_id:
            return True
        par = step.get("parallel")
        if isinstance(par, list) and agent_id in par:
            return True
        disp = step.get("dispatch")
        if isinstance(disp, dict):
            workers = disp.get("workers")
            if isinstance(workers, list) and agent_id in workers:
                return True
    return False


def step_ids(steps: List[Any]) -> Dict[str, int]:
    out: Dict[str, int] = {}
    if not isinstance(steps, list):
        return out
    for i, step in enumerate(steps):
        if isinstance(step, dict) and isinstance(step.get("id"), str):
            out[step["id"]] = i
    return out


def agent_ids(agents: List[Any]) -> Dict[str, int]:
    out: Dict[str, int] = {}
    if not isinstance(agents, list):
        return out
    for i, ag in enumerate(agents):
        if isinstance(ag, dict) and isinstance(ag.get("id"), str):
            out[ag["id"]] = i
    return out


def needs_graph_has_cycle(steps: List[dict], sid_map: Dict[str, int]) -> bool:
    graph: Dict[str, List[str]] = {}
    for step in steps:
        if not isinstance(step, dict):
            continue
        sid = step.get("id")
        if not isinstance(sid, str):
            continue
        needs = step.get("needs", [])
        if needs is None:
            needs = []
        if not isinstance(needs, list):
            continue
        graph[sid] = [n for n in needs if isinstance(n, str)]

    visited: Set[str] = set()
    stack: Set[str] = set()

    def dfs(node: str) -> bool:
        if node in stack:
            return True
        if node in visited:
            return False
        visited.add(node)
        stack.add(node)
        for n in graph.get(node, []):
            if n in sid_map and dfs(n):
                return True
        stack.remove(node)
        return False

    for sid in graph:
        if sid in sid_map and dfs(sid):
            return True
    return False


def transitive_needs(step_id: str, steps: List[dict], sid_map: Dict[str, int]) -> Set[str]:
    by_id = {s["id"]: s for s in steps if isinstance(s, dict) and isinstance(s.get("id"), str)}
    seen: Set[str] = set()
    first = by_id.get(step_id, {}).get("needs")
    stack = list(first) if isinstance(first, list) else []
    while stack:
        n = stack.pop()
        if not isinstance(n, str) or n in seen or n not in sid_map:
            continue
        seen.add(n)
        nxt = by_id.get(n, {}).get("needs")
        stack.extend(nxt if isinstance(nxt, list) else [])
    return seen


def validate_spec_file(spec_path: Path) -> Tuple[List[Finding], Optional[dict]]:
    findings: List[Finding] = []
    spec_str = str(spec_path)
    try:
        raw = spec_path.read_bytes()
    except OSError:
        print(f"usage: cannot read spec file {spec_str}", file=sys.stderr)
        sys.exit(2)

    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        findings.append(
            Finding("error", "S001", spec_str, "invalid YAML at line 1")
        )
        return findings, None

    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as e:
        line = 1
        if hasattr(e, "problem_mark") and e.problem_mark:
            line = e.problem_mark.line + 1
        findings.append(
            Finding(
                "error",
                "S001",
                spec_str,
                f"invalid YAML at line {line}",
            )
        )
        return findings, None

    if data is None:
        data = {}
    if not isinstance(data, dict):
        findings.append(
            Finding("error", "S006", spec_loc(spec_str, "root"), "spec must be a YAML mapping")
        )
        return findings, None

    # S029 basename
    if spec_path.name.endswith(".crew.yaml"):
        base = spec_path.name[: -len(".crew.yaml")]
        name_val = data.get("name")
        if isinstance(name_val, str) and base != name_val:
            findings.append(
                Finding(
                    "error",
                    "S029",
                    spec_str,
                    f"basename must match name '{name_val}'",
                )
            )

    for key in data:
        if key not in TOP_KEYS:
            findings.append(
                Finding(
                    "error",
                    "S002",
                    spec_loc(spec_str, key),
                    f"unknown key '{key}'",
                )
            )

    required_top = ["schema", "name", "description", "pattern", "harnesses", "agents", "steps"]
    for rk in required_top:
        if rk not in data:
            findings.append(
                Finding(
                    "error",
                    "S005",
                    spec_loc(spec_str, rk),
                    f"missing required key '{rk}'",
                )
            )

    if "schema" in data and data["schema"] != 1:
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_str, "schema"),
                "must be 1",
            )
        )

    if "name" in data:
        check_name_id(findings, spec_str, data["name"], "name")

    if "description" in data:
        desc = data["description"]
        if not isinstance(desc, str) or len(desc) < 1 or len(desc) > 1024:
            findings.append(
                Finding(
                    "error",
                    "S006",
                    spec_loc(spec_str, "description"),
                    "must be 1–1024 characters",
                )
            )

    if "pattern" in data:
        check_string_enum(
            findings,
            spec_str,
            "pattern",
            data["pattern"],
            PATTERNS,
            f"must be one of {', '.join(sorted(PATTERNS))}",
        )

    harness_list: List[str] = []
    if "harnesses" in data:
        h = data["harnesses"]
        if not isinstance(h, list) or len(h) == 0:
            findings.append(
                Finding(
                    "error",
                    "S006",
                    spec_loc(spec_str, "harnesses"),
                    "must be a non-empty list",
                )
            )
        else:
            seen_h: Set[str] = set()
            for i, item in enumerate(h):
                if not isinstance(item, str):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"harnesses[{i}]"),
                            f"must be one of {', '.join(sorted(HARNESSES))}",
                        )
                    )
                    continue
                if item not in HARNESSES:
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"harnesses[{i}]"),
                            f"must be one of {', '.join(sorted(HARNESSES))}",
                        )
                    )
                elif item in seen_h:
                    findings.append(
                        Finding(
                            "error",
                            "S033",
                            spec_loc(spec_str, f"harnesses[{i}]"),
                            f"duplicate value '{item}'",
                        )
                    )
                else:
                    seen_h.add(item)
                    harness_list.append(str(item))

    if "invocation" in data:
        check_string_enum(
            findings,
            spec_str,
            "invocation",
            data["invocation"],
            INVOCATIONS,
            "must be manual or auto",
        )

    if "on_exhaustion" in data:
        check_string_enum(
            findings,
            spec_str,
            "on_exhaustion",
            data["on_exhaustion"],
            ON_EXHAUSTION,
            "must be ask-user or stop",
        )

    if "cursor_rule" in data and not isinstance(data["cursor_rule"], bool):
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_str, "cursor_rule"),
                "must be a boolean",
            )
        )

    if "workdir" in data and not isinstance(data["workdir"], str):
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_str, "workdir"),
                "must be a string",
            )
        )

    models_map = data.get("models")
    if models_map is not None:
        if not isinstance(models_map, dict):
            findings.append(
                Finding(
                    "error",
                    "S006",
                    spec_loc(spec_str, "models"),
                    "must be a mapping",
                )
            )
            models_map = {}
        else:
            for hk, hv in models_map.items():
                if not isinstance(hk, str):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, "models"),
                            "must use string harness keys",
                        )
                    )
                    continue
                if hk not in HARNESSES:
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"models.{hk}"),
                            "unknown harness key",
                        )
                    )
                    continue
                if not isinstance(hv, dict):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"models.{hk}"),
                            "must be a mapping",
                        )
                    )
                    continue
                for mk, mv in hv.items():
                    if not isinstance(mk, str):
                        findings.append(
                            Finding(
                                "error",
                                "S006",
                                spec_loc(spec_str, f"models.{hk}"),
                                "must use string keys",
                            )
                        )
                        continue
                    if mk not in MODEL_HARNESS_KEYS:
                        findings.append(
                            Finding(
                                "error",
                                "S037",
                                spec_loc(spec_str, f"models.{hk}"),
                                f"unknown key '{mk}'",
                            )
                        )
                    elif mk in ("frontier", "light", "fast", "verified") and not isinstance(
                        mv, str
                    ):
                        findings.append(
                            Finding(
                                "error",
                                "S006",
                                spec_loc(spec_str, f"models.{hk}.{mk}"),
                                "must be a string",
                            )
                        )
                    elif isinstance(mv, str) and "<" in mv and ">" in mv:
                        findings.append(
                            Finding(
                                "warn",
                                "S040",
                                spec_loc(spec_str, f"models.{hk}.{mk}"),
                                "placeholder value; verify the model ID live and replace it",
                            )
                        )

    agents_raw = data.get("agents")
    steps_raw = data.get("steps")
    agents: List[dict] = agents_raw if isinstance(agents_raw, list) else []
    steps: List[dict] = [s for s in (steps_raw if isinstance(steps_raw, list) else []) if isinstance(s, dict)]

    if isinstance(agents_raw, list):
        n_ag = len(agents_raw)
        if n_ag < 1 or n_ag > 8:
            findings.append(
                Finding(
                    "error",
                    "S032",
                    spec_loc(spec_str, "agents"),
                    "must have 1–8 agents",
                )
            )
        if n_ag > 6:
            findings.append(
                Finding(
                    "warn",
                    "S028",
                    spec_loc(spec_str, "agents"),
                    f"crew has {n_ag} agents (warning above 6)",
                )
            )
    elif "agents" in data:
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_str, "agents"),
                "must be a list",
            )
        )

    if isinstance(steps_raw, list):
        if len(steps_raw) == 0:
            findings.append(
                Finding(
                    "error",
                    "S006",
                    spec_loc(spec_str, "steps"),
                    "must have at least one step",
                )
            )
    elif "steps" in data:
        findings.append(
            Finding(
                "error",
                "S006",
                spec_loc(spec_str, "steps"),
                "must be a list",
            )
        )

    aid_map = agent_ids(agents_raw if isinstance(agents_raw, list) else [])
    sid_map = step_ids(steps_raw if isinstance(steps_raw, list) else [])

    seen_agent_ids: Dict[str, int] = {}
    if isinstance(agents_raw, list):
        for i, ag in enumerate(agents_raw):
            prefix = f"agents[{i}]"
            if not isinstance(ag, dict):
                findings.append(
                    Finding(
                        "error",
                        "S006",
                        spec_loc(spec_str, prefix),
                        "must be a mapping",
                    )
                )
                continue
            for key in ag:
                if key not in AGENT_KEYS:
                    findings.append(
                        Finding(
                            "error",
                            "S003",
                            spec_loc(spec_str, prefix),
                            f"unknown key '{key}'",
                        )
                    )
            for rk in ("id", "description", "instructions"):
                if rk not in ag:
                    findings.append(
                        Finding(
                            "error",
                            "S005",
                            spec_loc(spec_str, f"{prefix}.{rk}"),
                            f"missing required key '{rk}'",
                        )
                    )
            if "id" in ag:
                aid = ag["id"]
                if isinstance(aid, str):
                    if aid in seen_agent_ids:
                        findings.append(
                            Finding(
                                "error",
                                "S008",
                                spec_loc(spec_str, "agents"),
                                f"duplicate id '{aid}'",
                            )
                        )
                    else:
                        seen_agent_ids[aid] = i
                check_name_id(findings, spec_str, ag.get("id"), f"{prefix}.id")
            if "description" in ag:
                d = ag["description"]
                if not isinstance(d, str) or len(d) < 1 or len(d) > 1024:
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.description"),
                            "must be 1–1024 characters",
                        )
                    )
            kind = ag.get("kind", "worker")
            if "kind" in ag:
                kind_val = ag["kind"]
                if not isinstance(kind_val, str):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.kind"),
                            f"must be one of {', '.join(sorted(KINDS))}",
                        )
                    )
                    kind = "worker"
                elif kind_val not in KINDS:
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.kind"),
                            f"must be one of {', '.join(sorted(KINDS))}",
                        )
                    )
                    kind = "worker"
                else:
                    kind = kind_val
            tier = ag.get("tier", "inherit")
            if "tier" in ag:
                tier_val = ag["tier"]
                if not isinstance(tier_val, str):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.tier"),
                            f"must be one of {', '.join(sorted(TIERS))}",
                        )
                    )
                    tier = "inherit"
                elif tier_val not in TIERS:
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.tier"),
                            f"must be one of {', '.join(sorted(TIERS))}",
                        )
                    )
                    tier = "inherit"
                else:
                    tier = tier_val
            if "run" in ag:
                run_val = ag["run"]
                if check_string_enum(
                    findings,
                    spec_str,
                    f"{prefix}.run",
                    run_val,
                    RUNS,
                    f"must be one of {', '.join(sorted(RUNS))}",
                ) and run_val == "inline":
                    if kind != "worker":
                        findings.append(
                            Finding(
                                "error",
                                "S041",
                                spec_loc(spec_str, f"{prefix}.run"),
                                "run inline is allowed only on kind worker",
                            )
                        )
                    if tier != "inherit":
                        findings.append(
                            Finding(
                                "error",
                                "S042",
                                spec_loc(spec_str, f"{prefix}.run"),
                                "run inline requires tier inherit",
                            )
                        )
            tools = ag.get("tools", ["read", "search"])
            if "tools" in ag:
                if not isinstance(tools, list):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.tools"),
                            "must be a list",
                        )
                    )
                    tools = []
                else:
                    for ti, t in enumerate(tools):
                        if not isinstance(t, str):
                            findings.append(
                                Finding(
                                    "error",
                                    "S006",
                                    spec_loc(spec_str, f"{prefix}.tools[{ti}]"),
                                    "must be a string",
                                )
                            )
                            continue
                        if t not in TOOLS:
                            findings.append(
                                Finding(
                                    "error",
                                    "S026",
                                    spec_loc(spec_str, f"{prefix}.tools[{ti}]"),
                                    f"unknown tool '{t}'",
                                )
                            )
            has_edit = isinstance(tools, list) and "edit" in tools
            inputs = ag.get("inputs", [])
            if inputs is None:
                inputs = []
            if "inputs" in ag:
                if not isinstance(inputs, list):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.inputs"),
                            "must be a list",
                        )
                    )
                elif isinstance(inputs, list):
                    for ii, in_item in enumerate(inputs):
                        if not isinstance(in_item, str):
                            findings.append(
                                Finding(
                                    "error",
                                    "S006",
                                    spec_loc(spec_str, f"{prefix}.inputs[{ii}]"),
                                    "must be a string",
                                )
                            )
            outputs = ag.get("outputs", [])
            if outputs is None:
                outputs = []
            s039_at_outputs = False
            if "outputs" in ag and not isinstance(outputs, list):
                findings.append(
                    Finding(
                        "error",
                        "S006",
                        spec_loc(spec_str, f"{prefix}.outputs"),
                        "must be a list",
                    )
                )
            elif isinstance(outputs, list):
                for oi, out_item in enumerate(outputs):
                    if not isinstance(out_item, str):
                        findings.append(
                            Finding(
                                "error",
                                "S006",
                                spec_loc(spec_str, f"{prefix}.outputs[{oi}]"),
                                "must be a string",
                            )
                        )
                if len(outputs) > 0 and not has_edit:
                    s039_at_outputs = True
                    findings.append(
                        Finding(
                            "error",
                            "S039",
                            spec_loc(spec_str, f"{prefix}.outputs"),
                            "outputs require edit in tools",
                        )
                    )
            if kind == "planner" and not has_edit and not s039_at_outputs:
                findings.append(
                    Finding(
                        "error",
                        "S039",
                        spec_loc(spec_str, f"{prefix}.tools"),
                        "outputs require edit in tools",
                    )
                )
            if kind == "evaluator" and has_edit:
                findings.append(
                    Finding(
                        "error",
                        "S024",
                        spec_loc(spec_str, f"{prefix}.tools"),
                        "evaluator must not list edit",
                    )
                )
            if kind == "evaluator" and isinstance(tools, list) and "shell" in tools:
                findings.append(
                    Finding(
                        "warn",
                        "S025",
                        spec_loc(spec_str, f"{prefix}.tools"),
                        "shell on evaluator is discouraged",
                    )
                )
            if "instructions" in ag:
                ins = ag["instructions"]
                if not isinstance(ins, str) or len(ins.strip()) == 0:
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.instructions"),
                            "must be non-empty",
                        )
                    )

    seen_step_ids: Dict[str, int] = {}
    if isinstance(steps_raw, list):
        for i, step in enumerate(steps_raw):
            prefix = f"steps[{i}]"
            if not isinstance(step, dict):
                findings.append(
                    Finding(
                        "error",
                        "S006",
                        spec_loc(spec_str, prefix),
                        "must be a mapping",
                    )
                )
                continue
            for key in step:
                if key not in STEP_KEYS:
                    findings.append(
                        Finding(
                            "error",
                            "S004",
                            spec_loc(spec_str, prefix),
                            f"unknown key '{key}'",
                        )
                    )
            if "id" not in step:
                findings.append(
                    Finding(
                        "error",
                        "S005",
                        spec_loc(spec_str, f"{prefix}.id"),
                        "missing required key 'id'",
                    )
                )
            else:
                sid = step["id"]
                if isinstance(sid, str):
                    if sid in seen_step_ids:
                        findings.append(
                            Finding(
                                "error",
                                "S008",
                                spec_loc(spec_str, "steps"),
                                f"duplicate id '{sid}'",
                            )
                        )
                    else:
                        seen_step_ids[sid] = i
                check_name_id(findings, spec_str, step.get("id"), f"{prefix}.id")

            has_agent = "agent" in step and step["agent"] is not None
            has_parallel = "parallel" in step and step["parallel"] is not None
            if has_agent == has_parallel:
                findings.append(
                    Finding(
                        "error",
                        "S030",
                        spec_loc(spec_str, prefix),
                        "set exactly one of agent or parallel",
                    )
                )
            if has_parallel:
                par = step["parallel"]
                if not isinstance(par, list) or len(par) < 2:
                    findings.append(
                        Finding(
                            "error",
                            "S031",
                            spec_loc(spec_str, f"{prefix}.parallel"),
                            "must list at least two agents",
                        )
                    )
                elif isinstance(par, list):
                    for pi, pid in enumerate(par):
                        if not isinstance(pid, str):
                            findings.append(
                                Finding(
                                    "error",
                                    "S006",
                                    spec_loc(spec_str, f"{prefix}.parallel[{pi}]"),
                                    "must be a string",
                                )
                            )
                            continue
                        if pid not in aid_map:
                            findings.append(
                                Finding(
                                    "error",
                                    "S009",
                                    spec_loc(spec_str, f"{prefix}.parallel[{pi}]"),
                                    f"unknown agent '{pid}'",
                                )
                            )
                        else:
                            ai = aid_map[pid]
                            ag = agents_raw[ai] if isinstance(agents_raw, list) else {}
                            if isinstance(ag, dict) and ag.get("run") == "inline":
                                findings.append(
                                    Finding(
                                        "error",
                                        "S043",
                                        spec_loc(spec_str, f"agents[{ai}].run"),
                                        f"inline agent '{pid}' cannot be used in parallel or dispatch.workers",
                                    )
                                )
                            if isinstance(ag, dict) and ag.get("kind", "worker") != "worker":
                                findings.append(
                                    Finding(
                                        "error",
                                        "S038",
                                        spec_loc(spec_str, f"agents[{ai}]"),
                                        f"agent '{pid}' used in parallel must be kind worker",
                                    )
                                )
            if has_agent:
                aid_ref = step["agent"]
                if not isinstance(aid_ref, str):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.agent"),
                            "must be a string",
                        )
                    )
                elif aid_ref not in aid_map:
                    findings.append(
                        Finding(
                            "error",
                            "S009",
                            spec_loc(spec_str, f"{prefix}.agent"),
                            f"unknown agent '{aid_ref}'",
                        )
                    )

            needs = step.get("needs", [])
            if needs is None:
                needs = []
            if "needs" in step and not isinstance(needs, list):
                findings.append(
                    Finding(
                        "error",
                        "S006",
                        spec_loc(spec_str, f"{prefix}.needs"),
                        "must be a list",
                    )
                )
            elif isinstance(needs, list):
                for ni, nid in enumerate(needs):
                    if not isinstance(nid, str):
                        findings.append(
                            Finding(
                                "error",
                                "S006",
                                spec_loc(spec_str, f"{prefix}.needs[{ni}]"),
                                "must be a string",
                            )
                        )
                        continue
                    if nid not in sid_map:
                        findings.append(
                            Finding(
                                "error",
                                "S010",
                                spec_loc(spec_str, f"{prefix}.needs[{ni}]"),
                                f"unknown step '{nid}'",
                            )
                        )

            step_agent_kind = "worker"
            if has_agent and isinstance(step.get("agent"), str) and step["agent"] in aid_map:
                ag = agents_raw[aid_map[step["agent"]]]  # type: ignore[index]
                if isinstance(ag, dict):
                    step_agent_kind = ag.get("kind", "worker")

            if "routes" in step:
                if step_agent_kind != "router":
                    findings.append(
                        Finding(
                            "error",
                            "S015",
                            spec_loc(spec_str, prefix),
                            "routes forbidden for non-router agent",
                        )
                    )
                routes = step["routes"]
                if not isinstance(routes, dict) or len(routes) == 0:
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.routes"),
                            "must be a non-empty mapping",
                        )
                    )
                elif isinstance(routes, dict):
                    for rk, rv in routes.items():
                        if not isinstance(rv, str):
                            findings.append(
                                Finding(
                                    "error",
                                    "S006",
                                    spec_loc(spec_str, f"{prefix}.routes"),
                                    "route values must be strings",
                                )
                            )
                            continue
                        if rv not in sid_map:
                            findings.append(
                                Finding(
                                    "error",
                                    "S010",
                                    spec_loc(spec_str, f"{prefix}.routes"),
                                    f"unknown step '{rv}'",
                                )
                            )
            elif step_agent_kind == "router":
                findings.append(
                    Finding(
                        "error",
                        "S014",
                        spec_loc(spec_str, prefix),
                        "router step requires routes",
                    )
                )

            if "gate" in step:
                if step_agent_kind != "evaluator":
                    findings.append(
                        Finding(
                            "error",
                            "S013",
                            spec_loc(spec_str, prefix),
                            "gate forbidden for non-evaluator agent",
                        )
                    )
                gate = step["gate"]
                if not isinstance(gate, dict):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.gate"),
                            "must be a mapping",
                        )
                    )
                else:
                    for gk in gate:
                        if gk not in GATE_KEYS:
                            findings.append(
                                Finding(
                                    "error",
                                    "S035",
                                    spec_loc(spec_str, f"{prefix}.gate"),
                                    f"unknown key '{gk}'",
                                )
                            )
                    if "on_fail" not in gate:
                        findings.append(
                            Finding(
                                "error",
                                "S005",
                                spec_loc(spec_str, f"{prefix}.gate.on_fail"),
                                "missing required key 'on_fail'",
                            )
                        )
                    if "max_cycles" not in gate:
                        findings.append(
                            Finding(
                                "error",
                                "S005",
                                spec_loc(spec_str, f"{prefix}.gate.max_cycles"),
                                "missing required key 'max_cycles'",
                            )
                        )
                    mc = gate.get("max_cycles")
                    if "max_cycles" in gate and (
                        not isinstance(mc, int) or isinstance(mc, bool) or mc < 1 or mc > 5
                    ):
                        findings.append(
                            Finding(
                                "error",
                                "S018",
                                spec_loc(spec_str, f"{prefix}.gate.max_cycles"),
                                "must be 1–5",
                            )
                        )
                    on_fail = gate.get("on_fail")
                    sid = step.get("id")
                    if (
                        isinstance(on_fail, str)
                        and isinstance(sid, str)
                        and on_fail in sid_map
                        and sid in sid_map
                    ):
                        upstream = transitive_needs(sid, steps, sid_map)
                        if on_fail not in upstream:
                            findings.append(
                                Finding(
                                    "error",
                                    "S020",
                                    spec_loc(spec_str, f"{prefix}.gate.on_fail"),
                                    "gated step must transitively need on_fail step",
                                )
                            )
                    elif "on_fail" in gate and not isinstance(on_fail, str):
                        findings.append(
                            Finding(
                                "error",
                                "S006",
                                spec_loc(spec_str, f"{prefix}.gate.on_fail"),
                                "must be a string",
                            )
                        )
                    if isinstance(on_fail, str) and on_fail not in sid_map:
                        findings.append(
                            Finding(
                                "error",
                                "S010",
                                spec_loc(spec_str, f"{prefix}.gate.on_fail"),
                                f"unknown step '{on_fail}'",
                            )
                        )
            elif step_agent_kind == "evaluator":
                findings.append(
                    Finding(
                        "error",
                        "S012",
                        spec_loc(spec_str, prefix),
                        "evaluator step requires gate",
                    )
                )

            if "dispatch" in step:
                if step_agent_kind != "planner":
                    findings.append(
                        Finding(
                            "error",
                            "S017",
                            spec_loc(spec_str, prefix),
                            "dispatch forbidden for non-planner agent",
                        )
                    )
                disp = step["dispatch"]
                if not isinstance(disp, dict):
                    findings.append(
                        Finding(
                            "error",
                            "S006",
                            spec_loc(spec_str, f"{prefix}.dispatch"),
                            "must be a mapping",
                        )
                    )
                else:
                    for dk in disp:
                        if dk not in DISPATCH_KEYS:
                            findings.append(
                                Finding(
                                    "error",
                                    "S036",
                                    spec_loc(spec_str, f"{prefix}.dispatch"),
                                    f"unknown key '{dk}'",
                                )
                            )
                    if "workers" not in disp:
                        findings.append(
                            Finding(
                                "error",
                                "S005",
                                spec_loc(spec_str, f"{prefix}.dispatch.workers"),
                                "missing required key 'workers'",
                            )
                        )
                    if "max_tasks" not in disp:
                        findings.append(
                            Finding(
                                "error",
                                "S005",
                                spec_loc(spec_str, f"{prefix}.dispatch.max_tasks"),
                                "missing required key 'max_tasks'",
                            )
                        )
                    mt = disp.get("max_tasks")
                    if "max_tasks" in disp and (
                        not isinstance(mt, int) or isinstance(mt, bool) or mt < 1 or mt > 20
                    ):
                        findings.append(
                            Finding(
                                "error",
                                "S019",
                                spec_loc(spec_str, f"{prefix}.dispatch.max_tasks"),
                                "must be 1–20",
                            )
                        )
                    workers = disp.get("workers")
                    if "workers" in disp and not isinstance(workers, list):
                        findings.append(
                            Finding(
                                "error",
                                "S006",
                                spec_loc(spec_str, f"{prefix}.dispatch.workers"),
                                "must be a list",
                            )
                        )
                    elif isinstance(workers, list):
                        for wi, wid in enumerate(workers):
                            if not isinstance(wid, str):
                                findings.append(
                                    Finding(
                                        "error",
                                        "S006",
                                        spec_loc(spec_str, f"{prefix}.dispatch.workers[{wi}]"),
                                        "must be a string",
                                    )
                                )
                                continue
                            if wid not in aid_map:
                                findings.append(
                                    Finding(
                                        "error",
                                        "S009",
                                        spec_loc(spec_str, f"{prefix}.dispatch.workers[{wi}]"),
                                        f"unknown agent '{wid}'",
                                    )
                                )
                            else:
                                ai = aid_map[wid]
                                ag = agents_raw[ai] if isinstance(agents_raw, list) else {}
                                if isinstance(ag, dict) and ag.get("run") == "inline":
                                    findings.append(
                                        Finding(
                                            "error",
                                            "S043",
                                            spec_loc(spec_str, f"agents[{ai}].run"),
                                            f"inline agent '{wid}' cannot be used in parallel or dispatch.workers",
                                        )
                                    )
                                if isinstance(ag, dict) and ag.get("kind", "worker") != "worker":
                                    findings.append(
                                        Finding(
                                            "error",
                                            "S038",
                                            spec_loc(spec_str, f"agents[{ai}]"),
                                            f"agent '{wid}' used in dispatch.workers must be kind worker",
                                        )
                                    )
            elif step_agent_kind == "planner":
                findings.append(
                    Finding(
                        "error",
                        "S016",
                        spec_loc(spec_str, prefix),
                        "planner step requires dispatch",
                    )
                )

    if isinstance(steps_raw, list) and sid_map and steps:
        if needs_graph_has_cycle(steps, sid_map):
            findings.append(
                Finding(
                    "error",
                    "S011",
                    spec_loc(spec_str, "steps"),
                    "needs graph contains a cycle",
                )
            )

    # Route target needs router in needs (S021)
    if isinstance(steps_raw, list):
        for i, step in enumerate(steps_raw):
            if not isinstance(step, dict):
                continue
            routes = step.get("routes")
            if not isinstance(routes, dict):
                continue
            router_id = step.get("id")
            for target in routes.values():
                if not isinstance(target, str) or target not in sid_map:
                    continue
                ti = sid_map[target]
                target_step = steps_raw[ti]
                if not isinstance(target_step, dict):
                    continue
                tneeds = target_step.get("needs") if isinstance(target_step.get("needs"), list) else []
                if isinstance(router_id, str) and router_id not in tneeds:
                    findings.append(
                        Finding(
                            "error",
                            "S021",
                            spec_loc(spec_str, f"steps[{ti}].needs"),
                            "route target must list router step",
                        )
                    )

    # S023 unused agents
    if isinstance(agents_raw, list) and isinstance(steps_raw, list):
        for i, ag in enumerate(agents_raw):
            if not isinstance(ag, dict):
                continue
            aid = ag.get("id")
            if isinstance(aid, str) and not agent_used_in_steps(aid, steps_raw):
                findings.append(
                    Finding(
                        "error",
                        "S023",
                        spec_loc(spec_str, f"agents[{i}]"),
                        f"agent '{aid}' is never used",
                    )
                )

    # S044 knowledge-only worker that still runs as a subagent
    if isinstance(agents_raw, list) and isinstance(steps_raw, list) and len(agents_raw) > 1:
        blocked: Set[str] = set()
        on_fail_steps: Set[str] = set()
        rerun_steps: Set[str] = set()
        for st in steps_raw:
            if not isinstance(st, dict):
                continue
            par = st.get("parallel")
            if isinstance(par, list):
                blocked.update(x for x in par if isinstance(x, str))
            disp = st.get("dispatch")
            if isinstance(disp, dict) and isinstance(disp.get("workers"), list):
                blocked.update(x for x in disp["workers"] if isinstance(x, str))
            gate = st.get("gate")
            if isinstance(gate, dict) and isinstance(gate.get("on_fail"), str):
                on_fail_steps.add(gate["on_fail"])
                fail_id = gate["on_fail"]
                gate_id = st.get("id")
                if fail_id in sid_map and isinstance(gate_id, str) and gate_id in sid_map:
                    gate_needs = transitive_needs(gate_id, steps_raw, sid_map)
                    for other in steps_raw:
                        oid = other.get("id") if isinstance(other, dict) else None
                        if (
                            isinstance(oid, str)
                            and oid in gate_needs
                            and fail_id in transitive_needs(oid, steps_raw, sid_map)
                        ):
                            rerun_steps.add(oid)
        for st in steps_raw:
            if (
                isinstance(st, dict)
                and (st.get("id") in on_fail_steps or st.get("id") in rerun_steps)
                and isinstance(st.get("agent"), str)
            ):
                blocked.add(st["agent"])
        id_counts: Dict[str, int] = {}
        for ag in agents_raw:
            if isinstance(ag, dict) and isinstance(ag.get("id"), str):
                id_counts[ag["id"]] = id_counts.get(ag["id"], 0) + 1
        for i, ag in enumerate(agents_raw):
            if not isinstance(ag, dict):
                continue
            aid = ag.get("id")
            tools_v = ag.get("tools", ["read", "search"])
            outs_v = ag.get("outputs")
            if (
                isinstance(aid, str)
                and aid not in blocked
                and id_counts.get(aid, 0) == 1
                and ag.get("kind", "worker") == "worker"
                and ag.get("run", "subagent") == "subagent"
                and ag.get("tier", "inherit") == "inherit"
                and isinstance(tools_v, list)
                and all(t in ("read", "search") for t in tools_v)
                and not outs_v
            ):
                findings.append(
                    Finding(
                        "warn",
                        "S044",
                        spec_loc(spec_str, f"agents[{i}]"),
                        f"agent '{aid}' looks knowledge-only; consider run: inline",
                    )
                )

    # S027 missing models tiers
    if isinstance(agents_raw, list) and harness_list:
        for i, ag in enumerate(agents_raw):
            if not isinstance(ag, dict):
                continue
            tier = ag.get("tier", "inherit")
            if not isinstance(tier, str) or tier not in TIERS or tier == "inherit":
                continue
            if ag.get("run") == "inline":
                continue  # S042 already reports the tier
            for harness in harness_list:
                hmap = models_map.get(harness) if isinstance(models_map, dict) else None
                if not isinstance(hmap, dict) or tier not in hmap:
                    findings.append(
                        Finding(
                            "error",
                            "S027",
                            spec_loc(spec_str, f"models.{harness}"),
                            f"missing tier '{tier}' used by agent {ag.get('id', i)}",
                        )
                    )

    # Pattern rules S022
    pattern = data.get("pattern")
    if isinstance(pattern, str) and pattern in PATTERNS and isinstance(steps_raw, list):
        validate_pattern(findings, spec_str, pattern, steps_raw, sid_map)

    return findings, data


def validate_pattern(
    findings: List[Finding],
    spec_path: str,
    pattern: str,
    steps_raw: List[Any],
    sid_map: Dict[str, int],
) -> None:
    steps = [s for s in steps_raw if isinstance(s, dict)]

    def has_parallel(s: dict) -> bool:
        return "parallel" in s and s["parallel"] is not None

    def has_routes(s: dict) -> bool:
        return "routes" in s and s["routes"] is not None

    def has_dispatch(s: dict) -> bool:
        return "dispatch" in s and s["dispatch"] is not None

    def has_gate(s: dict) -> bool:
        return "gate" in s and s["gate"] is not None

    if pattern == "pipeline":
        for i, s in enumerate(steps_raw):
            if not isinstance(s, dict):
                continue
            if has_parallel(s) or has_routes(s) or has_dispatch(s):
                findings.append(
                    Finding(
                        "error",
                        "S022",
                        spec_loc(spec_path, "pattern"),
                        "pipeline must not use parallel steps",
                    )
                )
                break
        empty_needs = [s for s in steps if not (s.get("needs") or [])]
        if len(empty_needs) != 1:
            findings.append(
                Finding(
                    "error",
                    "S022",
                    spec_loc(spec_path, "pattern"),
                    "pipeline requires exactly one step with empty needs",
                )
            )
        needed_by: Dict[str, int] = {}
        for s in steps:
            for n in (s.get("needs") if isinstance(s.get("needs"), list) else []):
                if isinstance(n, str):
                    needed_by[n] = needed_by.get(n, 0) + 1
        for sid, cnt in needed_by.items():
            if cnt > 1:
                findings.append(
                    Finding(
                        "error",
                        "S022",
                        spec_loc(spec_path, "pattern"),
                        "pipeline step must not be needed by more than one successor",
                    )
                )
                break
        for s in steps:
            needs = s.get("needs") or []
            if isinstance(needs, list) and len(needs) > 1:
                findings.append(
                    Finding(
                        "error",
                        "S022",
                        spec_loc(spec_path, "pattern"),
                        "pipeline step must need exactly one predecessor",
                    )
                )
                break

    elif pattern == "router":
        route_steps = [s for s in steps if has_routes(s)]
        if len(route_steps) != 1:
            findings.append(
                Finding(
                    "error",
                    "S022",
                    spec_loc(spec_path, "pattern"),
                    "router requires exactly one step with routes",
                )
            )

    elif pattern == "fan-out":
        par_steps = [s for s in steps if has_parallel(s)]
        if not par_steps:
            findings.append(
                Finding(
                    "error",
                    "S022",
                    spec_loc(spec_path, "pattern"),
                    "fan-out requires at least one parallel step",
                )
            )
        else:
            par_ids = {s["id"] for s in par_steps if isinstance(s.get("id"), str)}
            found = False
            for s in steps:
                needs = s.get("needs") or []
                if isinstance(needs, list) and par_ids.intersection(n for n in needs if isinstance(n, str)):
                    found = True
                    break
            if not found:
                findings.append(
                    Finding(
                        "error",
                        "S022",
                        spec_loc(spec_path, "pattern"),
                        "fan-out requires a later step to need a parallel step",
                    )
                )

    elif pattern == "evaluator-optimizer":
        if not any(has_gate(s) for s in steps):
            findings.append(
                Finding(
                    "error",
                    "S022",
                    spec_loc(spec_path, "pattern"),
                    "evaluator-optimizer requires at least one gate",
                )
            )

    elif pattern == "orchestrator-workers":
        disp_steps = [s for s in steps if has_dispatch(s)]
        if len(disp_steps) != 1:
            findings.append(
                Finding(
                    "error",
                    "S022",
                    spec_loc(spec_path, "pattern"),
                    "orchestrator-workers requires exactly one dispatch step",
                )
            )


def inline_agent_ids(data: dict) -> List[str]:
    agents = data.get("agents") if isinstance(data.get("agents"), list) else []
    return [
        a["id"]
        for a in agents
        if isinstance(a, dict) and isinstance(a.get("id"), str) and a.get("run") == "inline"
    ]


def expected_generated_paths(data: dict) -> List[str]:
    if not isinstance(data, dict):
        return []
    name = data.get("name")
    if not isinstance(name, str):
        return []
    harnesses = data.get("harnesses") or []
    if not isinstance(harnesses, list):
        return []
    agents = data.get("agents") if isinstance(data.get("agents"), list) else []
    agent_ids_list = [
        a["id"]
        for a in agents
        if isinstance(a, dict) and isinstance(a.get("id"), str) and a.get("run") != "inline"
    ]
    inline_ids_list = inline_agent_ids(data)
    paths: List[str] = []
    cursor_rule = bool(data.get("cursor_rule", False))
    for h in harnesses:
        if h == "claude-code":
            for aid in agent_ids_list:
                paths.append(f".claude/agents/{aid}.md")
            for aid in inline_ids_list:
                paths.append(f".claude/skills/{name}/roles/{aid}.md")
            paths.append(f".claude/skills/{name}/SKILL.md")
        elif h == "cursor":
            for aid in agent_ids_list:
                paths.append(f".cursor/agents/{aid}.md")
            for aid in inline_ids_list:
                paths.append(f".cursor/skills/{name}/roles/{aid}.md")
            paths.append(f".cursor/skills/{name}/SKILL.md")
            if cursor_rule:
                paths.append(f".cursor/rules/{name}.mdc")
    return sorted(paths)


def parse_frontmatter(text: str) -> Tuple[Optional[dict], Optional[str], Optional[int]]:
    if not text.startswith("---"):
        return None, None, None
    end = text.find("\n---", 3)
    if end < 0:
        return None, None, None
    fm_text = text[3:end]
    body = text[end + 4 :]
    if body.startswith("\n"):
        body = body[1:]
    try:
        fm = yaml.safe_load(fm_text)
    except yaml.YAMLError:
        return None, fm_text, end
    if fm is not None and not isinstance(fm, dict):
        fm = None
    return fm, fm_text, end


def claude_tools_from_spec(tools: List[str]) -> str:
    mapping = {
        "read": ["Read"],
        "search": ["Grep", "Glob"],
        "edit": ["Edit", "Write"],
        "shell": ["Bash"],
        "web": ["WebFetch", "WebSearch"],
    }
    names: List[str] = []
    for t in tools:
        names.extend(mapping.get(t, []))
    seen: Set[str] = set()
    out: List[str] = []
    for n in names:
        if n not in seen:
            seen.add(n)
            out.append(n)
    return ", ".join(out)


def expected_model(data: dict, agent: dict, harness: str) -> str:
    tier = agent.get("tier", "inherit")
    if tier == "inherit":
        return "inherit"
    models = data.get("models") or {}
    hmap = models.get(harness) if isinstance(models, dict) else None
    if isinstance(hmap, dict) and isinstance(tier, str) and tier in hmap:
        return str(hmap[tier])
    return ""


def load_manifest_files(manifest_path: Path) -> Tuple[Dict[str, str], bool]:
    """Load manifest file map. Second value True if the file exists but is unreadable."""
    if not manifest_path.is_file():
        return {}, False
    try:
        text = manifest_path.read_bytes().decode("utf-8")
        mobj = json.loads(text)
    except (ValueError, OSError):
        return {}, True
    if not isinstance(mobj, dict) or not isinstance(mobj.get("files"), dict):
        return {}, True
    return {str(k): str(v) for k, v in mobj["files"].items()}, False


def manifest_unreadable_message(manifest_path: Path) -> str:
    return f"error: manifest is unreadable: {manifest_path}"


def manifest_stored_spec_sha256(manifest_path: Path) -> Optional[str]:
    if not manifest_path.is_file():
        return None
    try:
        mobj = json.loads(manifest_path.read_bytes().decode("utf-8"))
    except (ValueError, OSError):
        return None
    if not isinstance(mobj, dict):
        return None
    stored = mobj.get("spec_sha256")
    if not isinstance(stored, str):
        return None
    return stored


def spec_path_for_status(root: Path, spec_path: Path) -> str:
    root_res = root.resolve()
    spec_res = spec_path.resolve()
    try:
        return str(spec_res.relative_to(root_res))
    except ValueError:
        return str(spec_path)


def agent_by_id(data: dict, agent_id: str) -> Optional[dict]:
    for ag in data.get("agents") or []:
        if isinstance(ag, dict) and ag.get("id") == agent_id:
            return ag
    return None


def validate_tree(root: Path, spec_path: Path, data: dict) -> Tuple[List[Finding], Optional[int]]:
    findings: List[Finding] = []
    if not isinstance(data, dict):
        return findings, None
    crew_name = data.get("name")
    if not isinstance(crew_name, str):
        return findings, None
    harnesses = data.get("harnesses") or []
    invocation = data.get("invocation", "manual")
    agents_list = data.get("agents") or []
    manifest_path = root / ".agent-composer" / f"{crew_name}.manifest.json"
    manifest_files, manifest_bad = load_manifest_files(manifest_path)
    if manifest_bad:
        print(manifest_unreadable_message(manifest_path), file=sys.stderr)
        return findings, 2

    expected = expected_generated_paths(data)
    exp_set = set(expected)
    role_paths = {
        f".{h_dir}/skills/{crew_name}/roles/{aid}.md"
        for h_dir in ("claude", "cursor")
        for aid in inline_agent_ids(data)
    }

    for rel in expected:
        path = root / rel
        if not path.is_file():
            findings.append(
                Finding(
                    "error",
                    "T001",
                    rel,
                    "expected file missing",
                )
            )
            continue
        try:
            raw_bytes = path.read_bytes()
        except OSError:
            findings.append(
                Finding("error", "T001", rel, "expected file missing")
            )
            continue
        if rel in role_paths:
            try:
                role_text = raw_bytes.decode("utf-8")
            except UnicodeDecodeError:
                findings.append(Finding("error", "T015", rel, "not valid UTF-8"))
                continue
            check_role_file(
                findings,
                rel,
                role_text,
                crew_name,
                rel in manifest_files,
            )
            continue
        try:
            raw_bytes.decode("utf-8")
        except UnicodeDecodeError:
            findings.append(
                Finding("error", "T002", rel, "invalid frontmatter")
            )
            continue
        content = raw_bytes.decode("utf-8", errors="replace")

        fm, fm_raw, _ = parse_frontmatter(content)
        if fm is None:
            findings.append(
                Finding("error", "T002", rel, "invalid frontmatter")
            )
            continue

        # T012 collision check before accepting file
        marker_crew = None
        body_start = content.find("\n---", 3)
        if body_start >= 0:
            after = content[body_start + 4 :]
            if after.startswith("\n"):
                after = after[1:]
            first_line = after.split("\n", 1)[0] if after else ""
            m = MARKER_RE.match(first_line.strip())
            if m:
                marker_crew = m.group(1)
        in_manifest = rel in manifest_files
        if not in_manifest:
            if marker_crew is not None and marker_crew != crew_name:
                findings.append(
                    Finding(
                        "error",
                        "T012",
                        rel,
                        "collides with existing file not in manifest and without this crew's marker",
                    )
                )
            elif marker_crew is None:
                findings.append(
                    Finding(
                        "error",
                        "T012",
                        rel,
                        "collides with existing file not in manifest and without this crew's marker",
                    )
                )

        if rel.endswith(".mdc"):
            validate_cursor_rule(findings, rel, content, fm, crew_name)
            continue

        is_skill = "/skills/" in rel and rel.endswith("/SKILL.md")
        is_claude_agent = rel.startswith(".claude/agents/")
        is_cursor_agent = rel.startswith(".cursor/agents/")

        if is_skill:
            validate_orchestrator_skill(
                findings, rel, fm, crew_name, invocation, content
            )
            continue

        if is_claude_agent and "claude-code" in harnesses:
            stem = Path(rel).stem
            validate_claude_agent(findings, rel, fm, fm_raw, data, stem, agents_list)
            check_marker_and_body(findings, rel, content, crew_name)
        elif is_cursor_agent and "cursor" in harnesses:
            stem = Path(rel).stem
            validate_cursor_agent(findings, rel, fm, fm_raw, content, data, stem, agents_list)

    # T014 stale agent file for an inline agent
    for aid in inline_agent_ids(data):
        stale: List[str] = []
        if "claude-code" in harnesses:
            stale.append(f".claude/agents/{aid}.md")
        if "cursor" in harnesses:
            stale.append(f".cursor/agents/{aid}.md")
        for rel in stale:
            path = root / rel
            if not path.is_file():
                continue
            try:
                text = path.read_bytes().decode("utf-8", errors="replace")
            except OSError:
                continue
            if marker_crew_of(text) == crew_name:
                findings.append(
                    Finding(
                        "error",
                        "T014",
                        rel,
                        f"stale agent file for inline agent '{aid}'; delete it",
                    )
                )

    # T011 when cursor_rule expected but file missing handled by T001 on expected path

    return findings, None


def marker_crew_of(content: str) -> Optional[str]:
    """Crew named by the generated-by marker: first line, or first line after frontmatter."""
    text = content
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end < 0:
            return None
        text = text[end + 4 :]
        if text.startswith("\n"):
            text = text[1:]
    first = text.split("\n", 1)[0] if text else ""
    m = MARKER_RE.match(first.strip())
    return m.group(1) if m else None


def check_role_file(
    findings: List[Finding], rel: str, content: str, crew_name: str, in_manifest: bool
) -> None:
    """Role files have no frontmatter; the marker is line 1. Only T010, T009, T012 apply."""
    marker_crew = marker_crew_of(content)
    if not in_manifest and marker_crew != crew_name:
        findings.append(
            Finding(
                "error",
                "T012",
                rel,
                "collides with existing file not in manifest and without this crew's marker",
            )
        )
    first = content.split("\n", 1)[0].strip()
    if first != marker_line(crew_name):
        findings.append(
            Finding("error", "T010", rel, "missing generated-by marker line")
        )
    leftover = "{{" in content or any(
        ln.strip().startswith(("<!-- block:", "<!-- /block:")) for ln in content.splitlines()
    )
    if leftover:
        findings.append(
            Finding("error", "T009", rel, "contains {{ or block delimiter comment")
        )


def validate_orchestrator_skill(
    findings: List[Finding],
    rel: str,
    fm: dict,
    crew_name: str,
    invocation: str,
    content: str,
) -> None:
    allowed = set(SKILL_KEYS_BASE)
    if invocation == "manual":
        allowed.add(SKILL_KEY_MANUAL)
    for key in fm:
        if key not in allowed:
            findings.append(
                Finding(
                    "error",
                    "T004",
                    rel,
                    f"disallowed frontmatter key '{key}'",
                )
            )
    if invocation == "manual" and fm.get(SKILL_KEY_MANUAL) is not True:
        findings.append(
            Finding(
                "error",
                "T004",
                rel,
                f"missing required frontmatter key '{SKILL_KEY_MANUAL}'",
            )
        )
    if fm.get("name") != crew_name:
        findings.append(
            Finding(
                "error",
                "T003",
                rel,
                f"name must match crew name '{crew_name}'",
            )
        )
    check_marker_and_body(findings, rel, content, crew_name)
    line_count = content.count("\n") + (1 if content and not content.endswith("\n") else 0)
    if line_count > 500:
        findings.append(
            Finding("error", "T013", rel, "exceeds 500 lines")
        )


def validate_claude_agent(
    findings: List[Finding],
    rel: str,
    fm: dict,
    fm_raw: Optional[str],
    data: dict,
    stem: str,
    agents_list: List[Any],
) -> None:
    for key in fm:
        if key not in CLAUDE_AGENT_KEYS:
            findings.append(
                Finding(
                    "error",
                    "T004",
                    rel,
                    f"disallowed frontmatter key '{key}'",
                )
            )
    for req in CLAUDE_AGENT_KEYS:
        if req not in fm:
            findings.append(
                Finding(
                    "error",
                    "T004",
                    rel,
                    f"missing required frontmatter key '{req}'",
                )
            )
    if fm.get("name") != stem:
        findings.append(
            Finding(
                "error",
                "T003",
                rel,
                f"name must match file stem '{stem}'",
            )
        )
    ag = agent_by_id(data, stem)
    if ag:
        exp = expected_model(data, ag, "claude-code")
        if str(fm.get("model", "")) != exp:
            findings.append(
                Finding(
                    "error",
                    "T007",
                    rel,
                    "model does not match spec tier mapping",
                )
            )
        if ag.get("kind") == "evaluator":
            tools_str = str(fm.get("tools", ""))
            for wt in CLAUDE_WRITE_TOOLS:
                if re.search(rf"\b{re.escape(wt)}\b", tools_str):
                    findings.append(
                        Finding(
                            "error",
                            "T008",
                            rel,
                            "evaluator must not grant edit/write tools",
                        )
                    )
                    break


def validate_cursor_agent(
    findings: List[Finding],
    rel: str,
    fm: dict,
    fm_raw: Optional[str],
    content: str,
    data: dict,
    stem: str,
    agents_list: List[Any],
) -> None:
    allowed = set(CURSOR_AGENT_KEYS)
    for key in fm:
        if key not in allowed:
            if key == "tools":
                findings.append(
                    Finding(
                        "error",
                        "T006",
                        rel,
                        "Cursor agents must not declare tools:",
                    )
                )
            else:
                findings.append(
                    Finding(
                        "error",
                        "T004",
                        rel,
                        f"disallowed frontmatter key '{key}'",
                    )
                )
    for req in ("name", "description", "model"):
        if req not in fm:
            findings.append(
                Finding(
                    "error",
                    "T004",
                    rel,
                    f"missing required frontmatter key '{req}'",
                )
            )
    if fm.get("name") != stem:
        findings.append(
            Finding(
                "error",
                "T003",
                rel,
                f"name must match file stem '{stem}'",
            )
        )
    if fm_raw and "tools" not in fm:
        for line in fm_raw.splitlines():
            if line.strip().startswith("tools:"):
                findings.append(
                    Finding(
                        "error",
                        "T006",
                        rel,
                        "Cursor agents must not declare tools:",
                    )
                )
                break
    if fm_raw:
        for line in fm_raw.splitlines():
            if line.strip().startswith("model:"):
                val = line.split(":", 1)[1].strip()
                if val.startswith('"') or val.startswith("'"):
                    findings.append(
                        Finding(
                            "error",
                            "T005",
                            rel,
                            "Cursor model must be unquoted",
                        )
                    )
    ag = agent_by_id(data, stem)
    if ag:
        exp = expected_model(data, ag, "cursor")
        if str(fm.get("model", "")) != exp:
            findings.append(
                Finding(
                    "error",
                    "T007",
                    rel,
                    "model does not match spec tier mapping",
                )
            )
        if ag.get("kind") == "evaluator":
            tools = ag.get("tools", ["read", "search"])
            if not isinstance(tools, list):
                tools = []
            has_shell = "shell" in tools
            if not has_shell and fm.get("readonly") is not True:
                findings.append(
                    Finding(
                        "error",
                        "T008",
                        rel,
                        "evaluator must not grant edit/write tools",
                    )
                )
    check_marker_and_body(findings, rel, content, data.get("name", ""))


def validate_cursor_rule(
    findings: List[Finding], rel: str, content: str, fm: dict, crew_name: str
) -> None:
    if not rel.endswith(".mdc"):
        findings.append(
            Finding("error", "T011", rel, "requires alwaysApply true and .mdc extension")
        )
    if fm.get("alwaysApply") is not True:
        findings.append(
            Finding("error", "T011", rel, "requires alwaysApply true and .mdc extension")
        )
    check_marker_and_body(findings, rel, content, crew_name)


def check_marker_and_body(findings: List[Finding], rel: str, content: str, crew_name: str) -> None:
    fm, _, _ = parse_frontmatter(content)
    body_start = content.find("\n---", 3)
    if body_start < 0:
        return
    after = content[body_start + 4 :]
    if after.startswith("\n"):
        after = after[1:]
    lines = after.split("\n")
    if not lines:
        findings.append(
            Finding("error", "T010", rel, "missing generated-by marker line")
        )
    else:
        first = lines[0].strip()
        if not crew_name or first != marker_line(crew_name):
            findings.append(
                Finding("error", "T010", rel, "missing generated-by marker line")
            )
    full_body = after
    if "{{" in content:
        findings.append(
            Finding(
                "error",
                "T009",
                rel,
                "contains {{ or block delimiter comment",
            )
        )
    for line in full_body.splitlines():
        stripped = line.strip()
        if stripped.startswith("<!-- block:") or stripped.startswith("<!-- /block:"):
            findings.append(
                Finding(
                    "error",
                    "T009",
                    rel,
                    "contains {{ or block delimiter comment",
                )
            )
            break


def manifest_write(root: Path, spec_path: Path, data: dict) -> int:
    if not isinstance(data, dict):
        print("error: invalid spec", file=sys.stderr)
        return 1
    crew_name = data.get("name")
    if not isinstance(crew_name, str):
        print("error: spec missing name", file=sys.stderr)
        return 1
    expected = expected_generated_paths(data)
    files_map: Dict[str, str] = {}
    for rel in expected:
        path = root / rel
        if not path.is_file():
            print(f"error: missing generated file {rel}", file=sys.stderr)
            return 1
        files_map[rel] = sha256_file(path)
    spec_bytes = spec_path.read_bytes()
    doc = {
        "schema": 1,
        "crew": crew_name,
        "generator": f"agent-composer {skill_version()}",
        "spec_sha256": sha256_bytes(spec_bytes),
        "harnesses": list(data.get("harnesses") or []),
        "files": dict(sorted(files_map.items())),
    }
    out_dir = root / ".agent-composer"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"{crew_name}.manifest.json"
    out_path.write_text(
        json.dumps(doc, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return 0


def manifest_status(root: Path, spec_path: Path, data: dict) -> int:
    if not isinstance(data, dict):
        print("error: invalid spec", file=sys.stderr)
        return 1
    crew_name = data.get("name")
    if not isinstance(crew_name, str):
        return 1
    expected = expected_generated_paths(data)
    exp_set = set(expected)
    manifest_path = root / ".agent-composer" / f"{crew_name}.manifest.json"
    manifest_files, manifest_bad = load_manifest_files(manifest_path)
    if manifest_bad:
        print(manifest_unreadable_message(manifest_path), file=sys.stderr)
        return 2

    lines: List[Tuple[str, str]] = []
    all_paths = sorted(set(expected) | set(manifest_files.keys()))
    for rel in all_paths:
        in_exp = rel in exp_set
        in_man = rel in manifest_files
        on_disk = (root / rel).is_file()
        if in_exp and not on_disk:
            lines.append(("missing", rel))
        elif not in_exp and in_man:
            lines.append(("orphan", rel))
        elif in_exp and on_disk:
            if not in_man:
                lines.append(("new", rel))
            else:
                current = sha256_file(root / rel)
                if current != manifest_files[rel]:
                    lines.append(("edited", rel))
                else:
                    lines.append(("unchanged", rel))
    lines.sort(key=lambda x: x[1])
    exit_code = 0
    if manifest_path.is_file():
        stored_sha = manifest_stored_spec_sha256(manifest_path)
        current_sha = sha256_file(spec_path)
        if stored_sha is None or stored_sha != current_sha:
            print(f"spec-changed {spec_path_for_status(root, spec_path)}")
            exit_code = 1
    for state, rel in lines:
        print(f"{state} {rel}")
        if state != "unchanged":
            exit_code = 1
    return exit_code


def cmd_validate(args: List[str]) -> int:
    if len(args) < 1:
        print("usage: validate spec <spec.crew.yaml>", file=sys.stderr)
        print("       validate tree <project-root> <spec.crew.yaml>", file=sys.stderr)
        return 2
    sub = args[0]
    if sub == "spec":
        if len(args) != 2:
            print("usage: validate spec <spec.crew.yaml>", file=sys.stderr)
            return 2
        spec_path = Path(args[1])
        findings, _ = validate_spec_file(spec_path)
        return emit_validate(findings)
    if sub == "tree":
        if len(args) != 3:
            print("usage: validate tree <project-root> <spec.crew.yaml>", file=sys.stderr)
            return 2
        root = Path(args[1])
        spec_path = Path(args[2])
        findings, data = validate_spec_file(spec_path)
        if data is not None:
            tree_findings, early = validate_tree(root, spec_path, data)
            findings.extend(tree_findings)
            if early is not None:
                return early
        return emit_validate(findings)
    print("usage: validate spec <spec.crew.yaml>", file=sys.stderr)
    return 2


def cmd_manifest(args: List[str]) -> int:
    if len(args) < 1:
        print("usage: manifest write <project-root> <spec.crew.yaml>", file=sys.stderr)
        return 2
    sub = args[0]
    if sub == "write":
        if len(args) != 3:
            print("usage: manifest write <project-root> <spec.crew.yaml>", file=sys.stderr)
            return 2
        root = Path(args[1])
        spec_path = Path(args[2])
        findings, data = validate_spec_file(spec_path)
        if any(f.severity == "error" for f in findings):
            for f in sorted(findings, key=lambda x: (x.location, x.code)):
                if f.severity == "error":
                    print(f.line())
            return 1
        if data is None:
            return 1
        return manifest_write(root, spec_path, data)
    if sub == "status":
        if len(args) != 3:
            print("usage: manifest status <project-root> <spec.crew.yaml>", file=sys.stderr)
            return 2
        root = Path(args[1])
        spec_path = Path(args[2])
        _, data = validate_spec_file(spec_path)
        if data is None:
            return 1
        return manifest_status(root, spec_path, data)
    print("usage: manifest write <project-root> <spec.crew.yaml>", file=sys.stderr)
    return 2


def main() -> int:
    try:
        if len(sys.argv) < 2:
            print("usage: composer.py validate|manifest ...", file=sys.stderr)
            return 2
        cmd = sys.argv[1]
        rest = sys.argv[2:]
        if cmd == "validate":
            return cmd_validate(rest)
        if cmd == "manifest":
            return cmd_manifest(rest)
        print("usage: composer.py validate|manifest ...", file=sys.stderr)
        return 2
    except Exception as exc:
        print(f"error: internal: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
